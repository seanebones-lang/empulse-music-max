import type { NextConfig } from "next";

// Bundle analyzer configuration (optional - only if package is installed)
let withBundleAnalyzer = (config: NextConfig) => config;
if (process.env.ANALYZE === 'true') {
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    withBundleAnalyzer = require('@next/bundle-analyzer')({
      enabled: true,
    });
  } catch (error) {
    // Bundle analyzer not installed - skip it
    console.warn('@next/bundle-analyzer not installed. Run: npm install --legacy-peer-deps @next/bundle-analyzer --save-dev');
  }
}

